class RMSNorm(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.scale = dim ** 0.5
        self.g = nn.Parameter(torch.ones(1, dim, 1, 1))

    def forward(self, x):
        return torch.mul(torch.mul(F.normalize(x, dim = 1),self.g), self.scale) #reduce memory consumption

